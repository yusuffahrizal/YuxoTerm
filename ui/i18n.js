let lang = "en";

export const LANGUAGES = [
  { value: "system", labelKey: "lang.system" },
  { value: "en", label: "English" },
  { value: "id", label: "Bahasa Indonesia" },
];

export function resolveLanguage(setting) {
  if (setting === "en" || setting === "id") return setting;
  return (navigator.language || "en").toLowerCase().startsWith("id") ? "id" : "en";
}

export function setLanguage(next) {
  lang = STRINGS[next] ? next : "en";
  document.documentElement.lang = lang;
}

export const currentLanguage = () => lang;
export const locale = () => (lang === "id" ? "id-ID" : "en-US");

// Shortcut labels depend on the platform (⌘ on macOS, Ctrl+Shift elsewhere), so strings
// refer to them as {kb.<id>} and the labeler fills them in.
let keyLabeler = () => "";
export function setKeyLabeler(fn) {
  keyLabeler = fn;
}

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  s = s.replace(/\{kb\.(\w+)\}/g, (_, id) => keyLabeler(id));
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  return s;
}

// Translated name for a built-in guard rule; custom names pass through.
export function ruleName(name) {
  const key = `rule.${name}`;
  return STRINGS[lang][key] ?? name;
}

// Inverse of ruleName, so untouched built-in names are saved in English.
export function ruleNameKey(display) {
  for (const [key, value] of Object.entries(STRINGS[lang])) {
    if (key.startsWith("rule.") && value === display) return key.slice(5);
  }
  return display;
}

export function applyI18n(root = document) {
  for (const n of root.querySelectorAll("[data-i18n]")) n.textContent = t(n.dataset.i18n);
  for (const n of root.querySelectorAll("[data-i18n-html]")) n.innerHTML = t(n.dataset.i18nHtml);
  for (const n of root.querySelectorAll("[data-i18n-placeholder]")) n.placeholder = t(n.dataset.i18nPlaceholder);
  for (const n of root.querySelectorAll("[data-i18n-title]")) n.title = t(n.dataset.i18nTitle);
}
